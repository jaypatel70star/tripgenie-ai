export function matchCatalogCity(query: string): CatalogCity | null {
  const q = query.toLowerCase();
  for (const city of DESTINATION_CATALOG) {
    if (
      q.includes(city.name.toLowerCase()) ||
      q.includes(city.country.toLowerCase()) ||
      (city.name === "Interlaken & Swiss Alps" && (q.includes("swiss") || q.includes("interlaken") || q.includes("switzerland") || q.includes("alps")))
    ) {
      return city;
    }
  }
  return null;
}

export function suggestDestinationsByProfile(
  interests: string[],
  budgetTier: BudgetTier,
  limit = 4
): DestinationSuggestion[] {
  const interestLower = interests.map((i) => i.toLowerCase());
  const scored = DESTINATION_CATALOG.map((city) => {
    let score = 76;
    for (const vibe of city.vibes) {
      if (interestLower.some((i) => i.includes(vibe) || vibe.includes(i))) {
        score += 7;
      }
    }
    if (budgetTier === "budget" && city.baseDailyUsd <= 90) score += 10;
    if (budgetTier === "moderate" && city.baseDailyUsd > 80 && city.baseDailyUsd <= 190) score += 8;
    if (budgetTier === "luxury" && city.baseDailyUsd >= 165) score += 8;
    return {
      city,
      score: Math.min(99, score),
    };
  })
    .sort((a, b) => b.score - a.score)
    .slice(0, limit);

  return scored.map(({ city, score }) => ({
    name: city.name,
    country: city.country,
    lat: city.lat,
    lng: city.lng,
    matchScore: score,
    bestTime: city.bestTime,
    estimatedDailyUsd: city.baseDailyUsd,
    tagline: city.tagline,
    highlights: city.activities.slice(0, 3).map((a) => a.title),
  }));
}
